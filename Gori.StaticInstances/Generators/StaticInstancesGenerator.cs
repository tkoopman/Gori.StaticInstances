using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;

using Gori.Common.Roslyn;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

using csb = Gori.CodeStringBuilder.CodeStringBuilder;

namespace Gori.StaticInstances.Generators;

/// <summary>
/// Source code generator for both <see cref="SingletonAttribute"/> and <see cref="StaticInstanceAttribute"/>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class StaticInstancesGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Pipeline 1 – one entry per [Singleton] class (singleton member only).
        IncrementalValuesProvider<InstanceInfo> singletonInfo = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                Const.SingletonAttributeFullName,
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, _) => Transforms.GetSingletonInstance(ctx))
            .Where(static info => info is not null)
            .Select(static (info, _) => info!);

        // Pipeline 2 – one entry per [StaticInstance] attribute, independent of whether the class also has [Singleton].
        IncrementalValuesProvider<InstanceInfo> staticInfo = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                Const.StaticInstanceAttributeFullName,
                predicate: static (node, _) => node is ConstructorDeclarationSyntax,
                transform: static (ctx, _) => Transforms.GetStaticInstances(ctx))
            .SelectMany(static (infoArray, _) => infoArray);

        IncrementalValuesProvider<ClassInfo> classes = singletonInfo.Collect()
            .Combine(staticInfo.Collect())
            .Combine(context.CompilationProvider)
            .SelectMany(static (input, _) => ClassInfo.Group(input.Left.Left, input.Left.Right, input.Right))
            .WithTrackingName("Classes");

        context.RegisterSourceOutput(classes, static (spc, info) => Execute(spc, info));
    }

    private static void Execute(SourceProductionContext spc, ClassInfo info)
    {
        EquatableTypeInfo type = info.Type;
        ImmutableArray<TypeDeclaration> declarations = type.Declarations;

        var sb = csb.CreateCSharpBuilder();
        _ = sb.WriteLine("// <auto-generated/>")
              .WriteLine("#nullable enable")
              .WriteLine();

        if (!string.IsNullOrEmpty(type.Namespace))
        {
            _ = sb.WriteLine($"namespace {type.Namespace}")
                  .WriteLine("{");
        }

        for (int i = 0; i < declarations.Length - 1; i++)
        {
            _ = sb.WriteLine($"partial {declarations[i].Keyword} {declarations[i].NameWithTypeParameters}")
                  .WriteLine("{");
        }

        TypeDeclaration self = declarations[^1];
        _ = sb.WriteLine($"partial {self.Keyword} {self.NameWithTypeParameters}")
              .WriteLine("{");

        _ = sb.WriteLineIf(info.Instances.Any(static instance => instance.AddConstructor), () => $$"""private {{type.Name}} () { }{{csb.BlankLinePost}}""");

        var instanceNames = new HashSet<string>(StringComparer.Ordinal);
        var allocatedNames = new HashSet<string>(info.ExistingMemberNames, StringComparer.Ordinal);
        allocatedNames.UnionWith(info.Instances.Select(static instance => instance.InstanceName));

        foreach (InstanceInfo instance in info.Instances)
        {
            // The analyzer reports duplicates; emission keeps only the first member of each name.
            if (!instanceNames.Add(instance.InstanceName))
            {
                continue;
            }

            string baseFieldName = $"_{char.ToLowerInvariant(instance.InstanceName[0])}{instance.InstanceName[1..]}";
            string fieldName = instance.InstanceType is InstanceType.Weak or InstanceType.WeakLockless or InstanceType.Lazy
                ? SIHelper.GetUniqueFieldName(allocatedNames, baseFieldName)
                : baseFieldName;

            string? weakLockFieldName = instance.InstanceType is InstanceType.Weak
                ? SIHelper.GetUniqueFieldName(allocatedNames, $"{fieldName}WeakLock")
                : null;

            WriteInstance(sb, instance, fieldName, weakLockFieldName);
            _ = sb.WriteLine();
        }

        _ = sb.WriteLine("}");

        for (int i = declarations.Length - 2; i >= 0; i--)
        {
            _ = sb.WriteLine("}");
        }

        if (!string.IsNullOrEmpty(type.Namespace))
        {
            _ = sb.WriteLine("}");
        }

        spc.AddSource($"{type.HintName}.{Const.HintSuffix}.g.cs", sb.ToString());
    }

    private static void WriteInstance(csb sb, InstanceInfo info, string fieldName, string? weakLockFieldName)
    {
        if (weakLockFieldName is not null)
        {
            _ = sb.WriteLine($$"""
                             #if NET9_0_OR_GREATER
                             private static readonly global::System.Threading.Lock {{weakLockFieldName}} = new global::System.Threading.Lock();
                             #else
                             private static readonly object {{weakLockFieldName}} = new object();
                             #endif
                             """)
                  .WriteLine(string.Empty);
        }

        string access      = info.Internal ? "internal" : "public";
        string ctorCall    = string.IsNullOrEmpty(info.ConstructorArgs) ? $"new {info.Type.NameWithTypeParameters}()" : $"new {info.Type.NameWithTypeParameters}({info.ConstructorArgs})";
        string summaryText = info.Comment is not null ? info.Comment : $"Gets {(info.IsSingleton ? "the singleton instance" : "a static instance")} of {info.Type.NameWithTypeParameters}";
        string comment     =
            $$"""
            /// <summary>
            /// {{FormatXmlDocSummaryText(summaryText)}}
            /// </summary>
            """;

        _ = info.InstanceType switch
        {
            InstanceType.Weak => sb.WriteLine($"private static readonly global::System.WeakReference<{info.Type.NameWithTypeParameters}> {fieldName} = new global::System.WeakReference<{info.Type.NameWithTypeParameters}>(null!);")
                                   .WriteLine(string.Empty)
                                   .WriteLine(comment)
                                   .WriteLine($$"""
                                         {{access}} static {{info.Type.NameWithTypeParameters}} {{info.InstanceName}}
                                         {
                                             get
                                             {
                                                 if ({{fieldName}}.TryGetTarget(out {{info.Type.NameWithTypeParameters}}? currentInstance))
                                                 {
                                                     return currentInstance;
                                                 }

                                                 lock({{weakLockFieldName}})
                                                 {
                                                     if ({{fieldName}}.TryGetTarget(out currentInstance))
                                                     {
                                                         return currentInstance;
                                                     }

                                                     currentInstance = {{ctorCall}};
                                                     {{fieldName}}.SetTarget(currentInstance);
                                                     return currentInstance;
                                                 }
                                             }
                                         }
                                         """),

            InstanceType.WeakLockless => sb.WriteLine($"private static readonly global::System.WeakReference<{info.Type.NameWithTypeParameters}> {fieldName} = new global::System.WeakReference<{info.Type.NameWithTypeParameters}>(null!);")
                                           .WriteLine(string.Empty)
                                           .WriteLine(comment)
                                           .WriteLine($$"""
                                                {{access}} static {{info.Type.NameWithTypeParameters}} {{info.InstanceName}}
                                                {
                                                    get
                                                    {
                                                        if ({{fieldName}}.TryGetTarget(out {{info.Type.NameWithTypeParameters}}? currentInstance))
                                                        {
                                                            return currentInstance;
                                                        }

                                                        currentInstance = {{ctorCall}};
                                                        {{fieldName}}.SetTarget(currentInstance);
                                                        return currentInstance;
                                                    }
                                                }
                                                """),

            InstanceType.Field => sb.WriteLine(comment)
                                    .WriteLine($"{access} static readonly {info.Type.NameWithTypeParameters} {info.InstanceName} = {ctorCall};"),

            InstanceType.Lazy => sb.WriteLine($"private static readonly global::System.Lazy<{info.Type.NameWithTypeParameters}> {fieldName} = new global::System.Lazy<{info.Type.NameWithTypeParameters}>(() => {ctorCall});")
                                   .WriteLine(comment)
                                   .WriteLine($"{access} static {info.Type.NameWithTypeParameters} {info.InstanceName} => {fieldName}.Value;"),

            _ => sb.WriteLine(comment)
                   .WriteLine($"{access} static {info.Type.NameWithTypeParameters} {info.InstanceName} {{ get; }} = {ctorCall};"),
        };
    }

    private static string FormatXmlDocSummaryText(string text)
    {
        string escaped = EscapeXmlCommentText(text)
            .Replace("\r\n", "\n")
            .Replace('\r', '\n');

        return escaped.Replace("\n", "\n/// ");
    }

    private static string EscapeXmlCommentText(string text)
        => text.Replace("&", "&amp;")
               .Replace("<", "&lt;")
               .Replace(">", "&gt;")
               .Replace("\"", "&quot;")
               .Replace("'", "&apos;");
}
